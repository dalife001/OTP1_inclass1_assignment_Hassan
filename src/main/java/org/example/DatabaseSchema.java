package org.example;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

final class DatabaseSchema {
    private DatabaseSchema() {
    }

    static void initialize(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS units (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        unit_key VARCHAR(40) NOT NULL UNIQUE,
                        category VARCHAR(20) NOT NULL,
                        symbol VARCHAR(10) NOT NULL
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS unit_translations (
                        unit_id INTEGER NOT NULL REFERENCES units(id) ON DELETE CASCADE,
                        lang VARCHAR(5) NOT NULL,
                        name VARCHAR(80) NOT NULL,
                        description VARCHAR(255) NOT NULL,
                        PRIMARY KEY (unit_id, lang)
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS temp_records (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        input_value DOUBLE PRECISION NOT NULL,
                        output_value DOUBLE PRECISION NOT NULL,
                        from_unit_id INTEGER NOT NULL REFERENCES units(id),
                        to_unit_id INTEGER NOT NULL REFERENCES units(id),
                        language VARCHAR(5) NOT NULL DEFAULT 'en',
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS measurement_units (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        unit_id INTEGER NOT NULL UNIQUE REFERENCES units(id)
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS travel_measurements (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        distance DOUBLE PRECISION NOT NULL CHECK (distance >= 0),
                        duration_seconds DOUBLE PRECISION NOT NULL CHECK (duration_seconds > 0),
                        speed DOUBLE PRECISION NOT NULL CHECK (speed >= 0),
                        unit_id INTEGER NOT NULL REFERENCES measurement_units(id),
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """);
        }
    }
}
